import { launch, openProfile } from './harness.mjs';
import { mkdirSync } from 'node:fs';
mkdirSync('shots', { recursive: true });
const arg = (k, d) => (process.argv.find((a) => a.startsWith(k + '=')) || '').split('=')[1] ?? d;
const tag = arg('tag', 'flow'); const dark = arg('dark', '0') === '1'; const w = Number(arg('w', 1400)); const h = Number(arg('h', 900));
const { ctx, id } = await launch({ viewport: { width: w, height: h } });
const page = await openProfile(ctx, 156);
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => { if (m.type() === 'error' && /chrome-extension|rofit/i.test(m.text())) errors.push(m.text()); });
const shot = (n) => page.screenshot({ path: `shots/${tag}-${n}.png` });
await page.waitForSelector('[data-rofit-tab]', { timeout: 25000 });
if (dark) await page.evaluate(() => { document.body.classList.remove('light-theme'); document.body.classList.add('dark-theme'); });
await page.locator('[data-rofit-tab]').first().click();
await page.waitForSelector('.rf-card', { timeout: 20000 });
await page.waitForTimeout(1200);
await shot('1-explorer');
// index everything, then Items view
await page.getByRole('button', { name: /^Index/ }).click();
await page.waitForSelector('.rf-seg button[aria-label="Items"], .rf-seg button:has-text("Items")', { timeout: 60000 });
await page.waitForFunction(() => !document.querySelector('.rf-progress'), null, { timeout: 90000 }).catch(() => {});
await page.waitForTimeout(800);
await page.locator('.rf-seg button:has-text("Items")').click();
await page.waitForTimeout(1800);
await shot('2-items');
await page.locator('.rf-seg button:has-text("Outfits")').click();
// select two + compare
await page.locator('.rf-pick').nth(0).click({ force: true });
await page.locator('.rf-pick').nth(1).click({ force: true });
await page.waitForTimeout(300);
await shot('3-selected');
await page.locator('.rf-tray .rf-btn.primary').click();
await page.waitForSelector('.rf-compare');
await page.waitForTimeout(4000);
await shot('4-compare');
await page.locator('.rf-cbar .rf-btn').first().click();
// open + save
await page.locator('.rf-tray .rf-btn:has-text("Clear")').click();
await page.locator('.rf-card').nth(1).click();
await page.waitForSelector('.rf-item', { timeout: 20000 });
await page.getByRole('button', { name: /^Save$/ }).click();
await page.waitForSelector('.rf-toast');
await page.waitForTimeout(600);
await shot('5-saved');
await page.getByRole('tab', { name: /Library/ }).click();
await page.waitForSelector('.rf-card');
await page.waitForTimeout(800);
await shot('6-library');
// search
await page.keyboard.press('/');
await page.keyboard.type('hat');
await page.waitForTimeout(500);
await shot('7-library-search');
// extension pages
const ws = await ctx.newPage();
await ws.goto(`chrome-extension://${id}/workspace.html#settings`);
await ws.waitForSelector('.rf-settings');
await ws.waitForTimeout(800);
await ws.screenshot({ path: `shots/${tag}-8-settings.png`, fullPage: true });
await ws.goto(`chrome-extension://${id}/workspace.html#welcome`);
await ws.waitForSelector('.rf-welcome');
await ws.screenshot({ path: `shots/${tag}-9-welcome.png` });
await ws.goto(`chrome-extension://${id}/workspace.html#library`);
await ws.waitForSelector('.rf-card');
await ws.waitForTimeout(500);
await ws.screenshot({ path: `shots/${tag}-10-library-page.png` });
const pp = await ctx.newPage();
await pp.setViewportSize({ width: 320, height: 330 });
await pp.goto(`chrome-extension://${id}/popup.html`);
await pp.waitForTimeout(600);
await pp.screenshot({ path: `shots/${tag}-11-popup.png` });
console.log('errors:', JSON.stringify(errors, null, 1));
await ctx.close();
